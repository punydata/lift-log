#!/usr/bin/env python3
"""Generates css/themes.css from the theme palette and checks text contrast (WCAG, 4.5:1).
Run: python3 scripts/themes.py   (prints a contrast report; fails if any pair is under 4.5)"""
import sys, os

THEMES = [  # id, name, dark?, bg, card, text, muted, accent, accent2
    ('chalk', 'Chalk', False, '#F2F3F5', '#FFFFFF', '#1B1F24', '#6B7280', '#2563EB', '#14B8A6'),
    ('oat-milk', 'Oat Milk', False, '#F5EFE4', '#FFFCF6', '#2E2620', '#7D7164', '#B5562F', '#5E8C6A'),
    ('sage', 'Sage', False, '#EBF0EA', '#FAFCF9', '#1F2A22', '#66756A', '#3F7A55', '#C4823A'),
    ('varsity', 'Varsity', False, '#F1E2B8', '#FBF2D8', '#2F2116', '#7E6447', '#9E2F2A', '#1F5C73'),
    ('iron', 'Iron', True, '#141618', '#1E2124', '#ECEAE6', '#8C9196', '#F2A541', '#5BC0BE'),
    ('blackout', 'Blackout', True, '#000000', '#111111', '#F5F5F5', '#8A8A8A', '#C6F432', '#38BDF8'),
    ('ember', 'Ember', True, '#1A1411', '#251C18', '#F3E9E2', '#A08F84', '#FF7A45', '#E9C46A'),
    ('deep-end', 'Deep End', True, '#0E1A28', '#16263A', '#E6EEF6', '#8597AB', '#4FC3F7', '#F78FB3'),
    ('afterhours', 'Afterhours', True, '#160F29', '#221A3D', '#F1EAFF', '#9C8FC0', '#FF4FA3', '#3DDBD9'),
]

def rgb(h): h = h.lstrip('#'); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
def hx(c): return '#%02X%02X%02X' % tuple(max(0, min(255, round(v))) for v in c)
def mix(a, b, t): a, b = rgb(a), rgb(b); return hx(tuple(a[i] + (b[i] - a[i]) * t for i in range(3)))
def lum(h):
    def ch(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(v) for v in rgb(h)); return 0.2126 * r + 0.7152 * g + 0.0722 * b
def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True); return (la + 0.05) / (lb + 0.05)
def reach(color, toward, against, target=4.5):
    """Move `color` toward `toward` until it has `target` contrast with every colour in `against`."""
    for i in range(0, 101):
        c = mix(color, toward, i / 100)
        if all(contrast(c, x) >= target for x in against): return c
    return toward
def ink(fill):
    return '#FFFFFF' if contrast('#FFFFFF', fill) >= contrast('#111111', fill) else '#111111'

def derive(t):
    tid, name, dark, bg, card, text, muted, a1, a2 = t
    v = {'bg': bg, 'card': card, 'text': text, 'accent': a1, 'accent2': a2}
    v['card2'] = mix(card, text, 0.07)
    v['line'] = mix(card, text, 0.14)
    v['field'] = mix(bg, '#000000', 0.35) if dark else mix(card, bg, 0.6)
    v['muted'] = reach(muted, text, [card, bg, v['card2'], v['field']])
    v['faint'] = mix(v['muted'], card, 0.35)
    v['accent-soft'] = mix(card, a1, 0.16)
    v['accent-text'] = reach(a1, text, [card, bg, v['accent-soft'], v['field']])
    v['accent2-text'] = reach(a2, text, [card, bg])
    v['accent-ink'] = ink(a1)
    v['accent2-ink'] = ink(a2)
    v['danger'] = reach('#FF6B6B' if dark else '#C62828', text, [card, bg, v['card2']])
    v['ok'] = reach('#3CCF7A' if dark else '#1E8E4E', text, [card, bg])
    v['grid'] = mix(card, text, 0.08)
    v['base'] = mix(card, text, 0.22)
    v['bar'] = mix(card, a2, 0.38)
    v['bar-text'] = reach(text, text, [v['bar']])
    v['switch-off'] = mix(card, text, 0.25)
    v['press'] = '1.18' if dark else '0.92'
    v['scheme'] = 'dark' if dark else 'light'
    return v

def checks(tid, v):
    pairs = [('text/bg', v['text'], v['bg']), ('text/card', v['text'], v['card']), ('text/card2', v['text'], v['card2']), ('text/field', v['text'], v['field']),
             ('muted/card', v['muted'], v['card']), ('muted/bg', v['muted'], v['bg']), ('accent-text/card', v['accent-text'], v['card']),
             ('accent-text/chip', v['accent-text'], v['accent-soft']), ('button label/accent', v['accent-ink'], v['accent']),
             ('button label/accent2', v['accent2-ink'], v['accent2']), ('danger/card', v['danger'], v['card']), ('rep label/bar', v['bar-text'], v['bar'])]
    return [(n, round(contrast(a, b), 2)) for n, a, b in pairs]

def main():
    out = ['/* Generated by scripts/themes.py. Edit the palette there, not here. */']
    report, bad = [], []
    for t in THEMES:
        v = derive(t)
        sel = ':root, html[data-theme="chalk"]' if t[0] == 'chalk' else f'html[data-theme="{t[0]}"]'
        body = ' '.join(f'--{k}: {val};' for k, val in v.items() if k != 'scheme')
        out.append(f'{sel} {{ color-scheme: {v["scheme"]}; {body} }}')
        res = checks(t[0], v)
        report.append(f'{t[1]:<11} ' + '  '.join(f'{n} {c}' for n, c in res))
        bad += [(t[1], n, c) for n, c in res if c < 4.5]
    root = os.path.join(os.path.dirname(__file__), '..', 'css', 'themes.css')
    open(root, 'w').write('\n'.join(out) + '\n')
    print('\n'.join(report))
    if bad:
        print('\nUNDER 4.5:1:', bad); sys.exit(1)
    print('\nAll pairs ≥ 4.5:1')

if __name__ == '__main__':
    main()
